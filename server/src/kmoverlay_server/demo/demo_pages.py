"""Synthetic comic pages drawn with Pillow.

They are generated by the code (no third-party art, no copyright issue) and
always look the same, so they are good for development and tests.
"""

import functools
import io
from dataclasses import dataclass

from PIL import Image, ImageDraw, ImageFont

PAGE_WIDTH = 800
PAGE_HEIGHT = 1200
MARGIN = 24
GUTTER = 16
TOP_PANEL_HEIGHT = 520
PANEL_BORDER_WIDTH = 5
BALLOON_BORDER_WIDTH = 3
BALLOON_FONT_SIZE = 22
BALLOON_TEXT_WIDTH_RATIO = 0.72
LINE_SPACING = 4

INK = (22, 22, 26)
PAPER = (255, 255, 255)
SCREENTONE = (241, 240, 236)
CHARACTER_DARK = (43, 43, 48)
CHARACTER_LIGHT = (85, 84, 90)

# Original lines written for this project, four balloons per page.
DIALOGUES: tuple[tuple[str, str, str, str], ...] = (
    (
        "YOU ARE LATE AGAIN!",
        "THE TRAIN WAS DELAYED, I SWEAR!",
        "ALWAYS THE SAME EXCUSE...",
        "THIS TIME IT IS TRUE!",
    ),
    ("DID YOU BRING THE MAP?", "I THOUGHT YOU HAD IT!", "THEN WE ARE LOST.", "LET'S ASK SOMEONE."),
    ("WHAT WAS THAT NOISE?", "PROBABLY JUST THE WIND.", "THE WIND DOES NOT KNOCK.", "...RUN!"),
    (
        "WE FINALLY MADE IT!",
        "IT IS SMALLER THAN IN THE PICTURES.",
        "BUT THE VIEW IS AMAZING.",
        "OKAY, YOU WIN THIS ONE.",
    ),
    (
        "I'M STARVING.",
        "THERE IS A NOODLE PLACE AROUND THE CORNER.",
        "IS IT ANY GOOD?",
        "THE BEST IN TOWN!",
    ),
    ("SEE YOU TOMORROW?", "SAME TIME, SAME PLACE.", "DON'T BE LATE THIS TIME.", "NO PROMISES!"),
)
PAGE_COUNT = len(DIALOGUES)

Box = tuple[int, int, int, int]


@dataclass(frozen=True)
class Balloon:
    """A speech balloon: its bounding box and the text inside it."""

    box: Box
    text: str


def demo_page_png(page_number: int) -> bytes:
    """PNG bytes of a demonstration page (1-based).

    Raises:
        ValueError: when the page does not exist.
    """
    if not 1 <= page_number <= PAGE_COUNT:
        raise ValueError(f"page_number must be between 1 and {PAGE_COUNT}")
    return _render_page_png(page_number)


@functools.cache
def _render_page_png(page_number: int) -> bytes:
    image = draw_demo_page(DIALOGUES[page_number - 1])
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def draw_demo_page(lines: tuple[str, str, str, str]) -> Image.Image:
    """Draws a three-panel page with characters and four balloons."""
    image = Image.new("RGB", (PAGE_WIDTH, PAGE_HEIGHT), PAPER)
    draw = ImageDraw.Draw(image)
    top, bottom_left, bottom_right = _panel_boxes()

    _draw_panel(draw, top, SCREENTONE)
    _draw_character(draw, top, left_side=True)
    _draw_character(draw, top, left_side=False)
    _draw_panel(draw, bottom_left, PAPER)
    _draw_character(draw, bottom_left, left_side=True)
    _draw_panel(draw, bottom_right, SCREENTONE)
    _draw_character(draw, bottom_right, left_side=False)

    for balloon in _balloons(top, bottom_left, bottom_right, lines):
        _draw_balloon(draw, balloon)
    return image


def _panel_boxes() -> tuple[Box, Box, Box]:
    top = (MARGIN, MARGIN, PAGE_WIDTH - MARGIN, MARGIN + TOP_PANEL_HEIGHT)
    bottom_top = top[3] + GUTTER
    middle = PAGE_WIDTH // 2
    bottom_left = (MARGIN, bottom_top, middle - GUTTER // 2, PAGE_HEIGHT - MARGIN)
    bottom_right = (middle + GUTTER // 2, bottom_top, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - MARGIN)
    return top, bottom_left, bottom_right


def _balloons(
    top: Box, bottom_left: Box, bottom_right: Box, lines: tuple[str, str, str, str]
) -> list[Balloon]:
    first, second, third, fourth = lines
    return [
        Balloon((top[0] + 260, top[1] + 30, top[0] + 540, top[1] + 170), first),
        Balloon((top[2] - 300, top[1] + 190, top[2] - 24, top[1] + 330), second),
        Balloon(
            (bottom_left[0] + 20, bottom_left[1] + 24, bottom_left[2] - 20, bottom_left[1] + 164),
            third,
        ),
        Balloon(
            (
                bottom_right[0] + 20,
                bottom_right[1] + 24,
                bottom_right[2] - 20,
                bottom_right[1] + 164,
            ),
            fourth,
        ),
    ]


def _draw_panel(draw: ImageDraw.ImageDraw, box: Box, fill: tuple[int, int, int]) -> None:
    draw.rectangle(box, fill=fill, outline=INK, width=PANEL_BORDER_WIDTH)


def _draw_character(draw: ImageDraw.ImageDraw, panel: Box, left_side: bool) -> None:
    """A simple silhouette (head and shoulders) standing at the bottom of a panel."""
    width = panel[2] - panel[0]
    center_x = panel[0] + (width * 0.28 if left_side else width * 0.72)
    color = CHARACTER_DARK if left_side else CHARACTER_LIGHT
    body_width = min(150, width * 0.36)
    body_top = panel[3] - 190
    draw.rounded_rectangle(
        (
            center_x - body_width / 2,
            body_top,
            center_x + body_width / 2,
            panel[3] - PANEL_BORDER_WIDTH,
        ),
        radius=body_width / 2,
        fill=color,
    )
    head_radius = body_width * 0.3
    head_center_y = body_top - head_radius - 8
    draw.ellipse(
        (
            center_x - head_radius,
            head_center_y - head_radius,
            center_x + head_radius,
            head_center_y + head_radius,
        ),
        fill=color,
    )


def _draw_balloon(draw: ImageDraw.ImageDraw, balloon: Balloon) -> None:
    draw.ellipse(balloon.box, fill=PAPER, outline=INK, width=BALLOON_BORDER_WIDTH)
    font = ImageFont.load_default(size=BALLOON_FONT_SIZE)
    max_width = (balloon.box[2] - balloon.box[0]) * BALLOON_TEXT_WIDTH_RATIO
    text = "\n".join(_wrap(balloon.text, font, max_width))
    center = ((balloon.box[0] + balloon.box[2]) / 2, (balloon.box[1] + balloon.box[3]) / 2)
    draw.multiline_text(
        center, text, fill=INK, font=font, anchor="mm", align="center", spacing=LINE_SPACING
    )


def _wrap(
    text: str, font: ImageFont.FreeTypeFont | ImageFont.ImageFont, max_width: float
) -> list[str]:
    lines: list[str] = []
    current = ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if current and font.getlength(candidate) > max_width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines
